	A.DESCR AS DESCR_ARMAZEM,
	B.NUMERO AS BL,
	C.BL AS LOTE,
	Y.QUANTIDADE AS QTDE,
	E.DESCR AS EMBALAGEM,
	C.MERCADORIA,
	C.MARCA,
	P.RAZAO AS IMPORTADOR,
	N.DESCR AS NAVIO,
	V.VIAGEM,
	CASE WHEN CNTR.DT_ENTRADA IS NULL THEN CONVERT(CHAR,C.DT_ENTRADA,106) ELSE CONVERT(CHAR,CNTR.DT_ENTRADA,106) END AS data_entrada,
	CNTR.DT_INICIO_DESOVA AS DATA_DESOVA,
	CNTR.ID_CONTEINER AS CNTR_DESOVA,
	ISNULL(C.PESO_BRUTO,0) AS peso,
	ISNULL(C.VOLUME_M3,0) AS VOLUME,
	Y.YARD AS POSICAO,
	'IPA-CS' AS FINALITY,
	ISNULL(TD.DESCR,'NOT DEFINED YET') AS TIPO_DOC,
	ISNULL(B.CANAL_SISCOMEX,0) AS CANAL_ALF,
	 CASE
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) < 2 then '00-02 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 2 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<4  then '02-04 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 4 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<6  then '04-06 days'
