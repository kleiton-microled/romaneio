			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 8 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<12  then '08-12 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 12 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<20  then '12-20 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 20 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<30  then '20-30 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 30 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<45  then '30-45 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 45 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<60  then '45-60 days'
			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 60   then '60 or + days'
	END
		AS dias_arm_faixa,
	CASE WHEN B.SEQ_FMA IS NULL THEN 0 ELSE 1 END AS FLAG_FMA,
	CASE WHEN B.TG IS NULL THEN 0 ELSE 1 END AS FLAG_TG,
	'' AS MOTIVO_PROX_MVTO,
	NULL AS HORAS_PROX_MVTO,
	'I' AS SISTEMA,
	'Y' + RTRIM(LTRIM (CONVERT(CHAR,Y.AUTONUM))) AS ID_GRAVACAO,
    C.IMO AS IMO ,
    VW2.NVOCC AS NVOCC,
    C.QUANTIDADE AS QTDE_CAPTADA,
	ISNULL(M.AUTONUM,0) AS MARCANTE,
	ISNULL(M.AUTONUM_CS_YARD,0) AS AUTONUM_CS_YARD
FROM
	SGIPA..TB_CARGA_SOLTA C INNER JOIN
	SGIPA..TB_BL B ON C.BL=B.AUTONUM INNER JOIN 
	SGIPA..TB_CARGA_SOLTA_YARD Y ON C.AUTONUM = Y.AUTONUM_CS LEFT JOIN
	SGIPA..DTE_TB_EMBALAGENS E ON C.EMBALAGEM=E.CODE LEFT JOIN 
	SGIPA..TB_CAD_PARCEIROS P ON B.IMPORTADOR=P.AUTONUM LEFT JOIN
	SGIPA..DTE_TB_VIAGENS V ON B.VIAGEM=V.VIAGEM LEFT JOIN
	SGIPA..DTE_TB_NAVIOS N ON V.NAVIO=N.CODE LEFT JOIN 
	SGIPA..TB_CNTR_BL CNTR ON C.CNTR=CNTR.AUTONUM LEFT JOIN
	SGIPA..TB_TIPOS_DOCUMENTOS TD ON B.TIPO_DOCUMENTO=TD.CODE  LEFT JOIN 
	SGIPA..VW_NVOCC_LOTE VW2 ON B.AUTONUM = VW2.BL_FILHOTE LEFT JOIN
	SGIPA..TB_ARMAZENS_IPA A ON Y.ARMAZEM=A.AUTONUM LEFT JOIN
	SGIPA..TB_MARCANTES M ON C.AUTONUM=M.AUTONUM_CARGA
WHERE
	C.FLAG_TERMINAL=1
	AND C.FLAG_HISTORICO=0 AND Y.QUANTIDADE >0
	AND ISNULL(M.AUTONUM_CS_YARD,0)=0

