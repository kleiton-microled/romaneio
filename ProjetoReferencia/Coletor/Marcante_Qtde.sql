			WHEN (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END) >= 6 and (GETDATE() - CASE WHEN CNTR.DT_ENTRADA IS NULL THEN C.DT_ENTRADA ELSE CNTR.DT_ENTRADA END)<8  then '06-08 days'
